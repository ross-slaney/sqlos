using System.Globalization;
using SqlOS.Database;
using SqlOS.Fga.Configuration;

namespace SqlOS.Fga.Indexing;

/// <summary>
/// Installs the shared resource ancestry used by native scope indexes. All columns and
/// tables emitted here belong to SqlOS; application tables retain their ResourceId link.
/// </summary>
/// <remarks>
/// Closure follows the point-check TVF exactly: inactive ancestors stop inheritance but
/// do not invalidate local grants below them. A detected cycle or a nonterminal ancestor
/// at the configured depth invalidates the entire target's ancestry.
///
/// Install and rebuild batches must run in one transaction. Rebuild is an explicit
/// initial-install/model-change operation, never an automatic startup repair scan.
/// Registered refresh statements receive the affected resource keys in
/// pg_temp.sqlos_fga_affected_resources(scope_key) or
/// #SqlOSFgaAffectedResources(ScopeKey), respectively.
/// </remarks>
internal static class SqlOSFgaClosureSql
{
    internal const string ClosureTable = "SqlOSFgaResourceClosure";
    internal const string GateTable = "SqlOSFgaTopologyGate";
    internal const string CatalogTable = "SqlOSFgaIndexCatalog";
    internal const string OwnersTable = "SqlOSFgaIndexOwners";

    internal static IReadOnlyList<string> Build(SqlOSFgaOptions options, bool postgres)
    {
        ArgumentNullException.ThrowIfNull(options);
        return postgres ? BuildPostgreSql(options) : BuildSqlServer(options);
    }

    internal static IReadOnlyList<string> Rebuild(SqlOSFgaOptions options, bool postgres)
    {
        ArgumentNullException.ThrowIfNull(options);
        var provider = Provider(postgres);
        var gate = provider.Qualify(options.Schema, GateTable);
        var resources = provider.Qualify(options.Schema, options.TableNames.Resources);
        var refresh = provider.Qualify(options.Schema, "fn_SqlOSFgaRefreshClosure");
        if (postgres)
        {
            return [$"""
                UPDATE {gate} SET "Version" = "Version" + 1 WHERE "Id" = 1;
                CREATE TEMP TABLE IF NOT EXISTS sqlos_fga_affected_resources (
                    scope_key bigint PRIMARY KEY) ON COMMIT DROP;
                TRUNCATE pg_temp.sqlos_fga_affected_resources;
                INSERT INTO pg_temp.sqlos_fga_affected_resources(scope_key)
                SELECT "ScopeKey" FROM {resources};
                SELECT {refresh}();
                """];
        }

        return [$"""
            UPDATE {gate} WITH (READCOMMITTEDLOCK)
            SET [Version] = [Version] + 1 WHERE [Id] = 1;
            CREATE TABLE #SqlOSFgaAffectedResources ([ScopeKey] bigint PRIMARY KEY);
            INSERT INTO #SqlOSFgaAffectedResources ([ScopeKey])
            SELECT [ScopeKey] FROM {resources} WITH (READCOMMITTEDLOCK);
            EXEC {refresh};
            DROP TABLE #SqlOSFgaAffectedResources;
            """];
    }

    private static IReadOnlyList<string> BuildPostgreSql(SqlOSFgaOptions options)
    {
        var provider = Provider(true);
        string Q(string name) => provider.Qualify(options.Schema, name);
        var resources = Q(options.TableNames.Resources);
        var types = Q(options.TableNames.ResourceTypes);
        var closure = Q(ClosureTable);
        var gate = Q(GateTable);
        var catalog = Q(CatalogTable);
        var owners = Q(OwnersTable);
        var depth = Math.Max(1, options.MaxResourceHierarchyDepth).ToString(CultureInfo.InvariantCulture);
        var refresh = Q("fn_SqlOSFgaRefreshClosure");
        var lockFunction = Q("fn_SqlOSFgaResourceGate");
        var changedFunction = Q("fn_SqlOSFgaResourcesChanged");

        return [
            $"""
            CREATE TABLE IF NOT EXISTS {gate} (
                "Id" integer PRIMARY KEY CHECK ("Id" = 1),
                "Version" bigint NOT NULL);
            INSERT INTO {gate} ("Id", "Version") VALUES (1, 0) ON CONFLICT DO NOTHING;
            UPDATE {gate} SET "Version" = "Version" + 1 WHERE "Id" = 1;
            ALTER TABLE {resources} ADD COLUMN IF NOT EXISTS "ScopeKey" bigint GENERATED BY DEFAULT AS IDENTITY;
            ALTER TABLE {resources} ADD COLUMN IF NOT EXISTS "ProjectionVersion" bigint NOT NULL DEFAULT 0;
            ALTER TABLE {types} ADD COLUMN IF NOT EXISTS "TypeKey" bigint GENERATED BY DEFAULT AS IDENTITY;
            CREATE UNIQUE INDEX IF NOT EXISTS "UX_SqlOSFgaResource_ScopeKey" ON {resources} ("ScopeKey");
            CREATE UNIQUE INDEX IF NOT EXISTS "UX_SqlOSFgaResourceType_TypeKey" ON {types} ("TypeKey");
            CREATE TABLE IF NOT EXISTS {closure} (
                "DescendantKey" bigint NOT NULL,
                "AncestorKey" bigint NOT NULL,
                "Depth" integer NOT NULL CHECK ("Depth" >= 0),
                PRIMARY KEY ("DescendantKey", "AncestorKey"));
            CREATE INDEX IF NOT EXISTS "IX_SqlOSFgaResourceClosure_Ancestor"
                ON {closure} ("AncestorKey", "DescendantKey");
            CREATE TABLE IF NOT EXISTS {catalog} (
                "Id" varchar(64) PRIMARY KEY,
                "ModelHash" varchar(64) NOT NULL,
                "RefreshSql" text NOT NULL,
                "DropSql" text NOT NULL DEFAULT '');
            CREATE TABLE IF NOT EXISTS {owners} (
                "OwnerKey" varchar(64) NOT NULL,
                "ProjectionId" varchar(64) NOT NULL REFERENCES {catalog} ("Id"),
                PRIMARY KEY ("OwnerKey", "ProjectionId"));
            CREATE INDEX IF NOT EXISTS "IX_SqlOSFgaIndexOwners_Projection"
                ON {owners} ("ProjectionId");
            """,
            $"""
            CREATE OR REPLACE FUNCTION {refresh}() RETURNS void
            LANGUAGE plpgsql VOLATILE AS $sqlos$
            DECLARE registered record;
            BEGIN
                -- Locks also validate ProjectionVersion updates against a frozen RR snapshot.
                PERFORM r."ScopeKey"
                FROM {resources} r
                JOIN pg_temp.sqlos_fga_affected_resources affected ON affected.scope_key = r."ScopeKey"
                ORDER BY r."ScopeKey" FOR UPDATE OF r;

                -- The FK can observe a parent committed after this transaction's frozen
                -- snapshot. Reparenting to that invisible new root must retry, not cache
                -- a falsely terminated ancestor chain. This applies to updates as well
                -- as insertion and includes SERIALIZABLE transactions.
                IF current_setting('transaction_isolation') IN ('repeatable read', 'serializable') AND EXISTS (
                    SELECT 1 FROM {resources} r
                    JOIN pg_temp.sqlos_fga_affected_resources affected ON affected.scope_key = r."ScopeKey"
                    LEFT JOIN {resources} parent ON parent."Id" = r."ParentId"
                    WHERE r."ParentId" IS NOT NULL AND parent."Id" IS NULL
                ) THEN
                    RAISE EXCEPTION 'SqlOS parent is not visible to the maintenance snapshot; retry the transaction.'
                        USING ERRCODE = '40001';
                END IF;

                IF EXISTS (
                    SELECT 1 FROM {resources} r
                    JOIN pg_temp.sqlos_fga_affected_resources affected ON affected.scope_key = r."ScopeKey"
                    LEFT JOIN {types} t ON t."Id" = r."ResourceTypeId"
                    WHERE t."Id" IS NULL
                ) THEN
                    RAISE EXCEPTION 'SqlOS resource type is not visible to the maintenance snapshot; retry the transaction.'
                        USING ERRCODE = '40001';
                END IF;

                DELETE FROM {closure} c
                USING pg_temp.sqlos_fga_affected_resources affected
                WHERE c."DescendantKey" = affected.scope_key;

                WITH RECURSIVE ancestors AS (
                    SELECT r."ScopeKey" AS descendant_key, r."ScopeKey" AS ancestor_key,
                           r."Id", r."ParentId", 0 AS depth,
                           ('|' || r."Id" || '|')::text AS visited_path, FALSE AS cycle_detected
                    FROM {resources} r
                    JOIN pg_temp.sqlos_fga_affected_resources affected ON affected.scope_key = r."ScopeKey"
                    WHERE r."IsActive" = TRUE
                    UNION ALL
                    SELECT a.descendant_key, parent."ScopeKey", parent."Id", parent."ParentId",
                           a.depth + 1, (a.visited_path || parent."Id" || '|')::text,
                           strpos(a.visited_path, '|' || parent."Id" || '|') > 0
                    FROM ancestors a
                    JOIN {resources} parent ON parent."Id" = a."ParentId"
                    WHERE a.depth < {depth} AND NOT a.cycle_detected AND parent."IsActive" = TRUE
                )
                INSERT INTO {closure} ("DescendantKey", "AncestorKey", "Depth")
                SELECT a.descendant_key, a.ancestor_key, a.depth
                FROM ancestors a
                WHERE NOT EXISTS (
                    SELECT 1 FROM ancestors invalid
                    WHERE invalid.descendant_key = a.descendant_key
                      AND (invalid.cycle_detected OR (invalid.depth = {depth} AND invalid."ParentId" IS NOT NULL))
                );

                FOR registered IN SELECT "RefreshSql" FROM {catalog}
                    WHERE "RefreshSql" <> '' ORDER BY "Id" LOOP
                    EXECUTE registered."RefreshSql";
                END LOOP;
            END;
            $sqlos$;
            """,
            $"""
            CREATE OR REPLACE FUNCTION {lockFunction}() RETURNS trigger
            LANGUAGE plpgsql VOLATILE AS $sqlos$
            BEGIN
                IF TG_OP = 'INSERT' THEN
                    PERFORM "Version" FROM {gate} WHERE "Id" = 1 FOR SHARE;
                ELSE
                    UPDATE {gate} SET "Version" = "Version" + 1 WHERE "Id" = 1;
                END IF;
                IF NOT FOUND THEN RAISE EXCEPTION 'The SqlOS resource topology gate is missing.'; END IF;
                RETURN NULL;
            END;
            $sqlos$;

            CREATE OR REPLACE FUNCTION {changedFunction}() RETURNS trigger
            LANGUAGE plpgsql VOLATILE AS $sqlos$
            DECLARE parent_key bigint;
            BEGIN
                -- Marker-only changes are intentional writes, not structural edits.
                IF TG_OP = 'UPDATE' THEN
                    IF NOT EXISTS (
                        SELECT 1 FROM sqlos_new_resources n
                        FULL JOIN sqlos_old_resources o ON o."ScopeKey" = n."ScopeKey"
                        WHERE n."Id" IS DISTINCT FROM o."Id"
                           OR n."ParentId" IS DISTINCT FROM o."ParentId"
                           OR n."IsActive" IS DISTINCT FROM o."IsActive"
                           OR n."ResourceTypeId" IS DISTINCT FROM o."ResourceTypeId"
                    ) THEN RETURN NULL; END IF;
                END IF;

                IF TG_OP = 'INSERT' THEN
                    -- A new child changes its parent's version so a stale-snapshot move
                    -- cannot overlook that child's existence while rebuilding a subtree.
                    IF EXISTS (
                        SELECT 1 FROM sqlos_new_resources n
                        LEFT JOIN {resources} parent ON parent."Id" = n."ParentId"
                        WHERE n."ParentId" IS NOT NULL AND parent."Id" IS NULL
                    ) AND current_setting('transaction_isolation') IN ('repeatable read', 'serializable') THEN
                        RAISE EXCEPTION 'SqlOS parent is not visible to the maintenance snapshot; retry the transaction.'
                            USING ERRCODE = '40001';
                    END IF;
                    FOR parent_key IN
                        SELECT DISTINCT parent."ScopeKey" FROM {resources} parent
                        JOIN sqlos_new_resources n ON n."ParentId" = parent."Id"
                        ORDER BY parent."ScopeKey"
                    LOOP
                        UPDATE {resources} SET "ProjectionVersion" = "ProjectionVersion" + 1
                        WHERE "ScopeKey" = parent_key;
                    END LOOP;
                END IF;

                CREATE TEMP TABLE IF NOT EXISTS sqlos_fga_affected_resources (
                    scope_key bigint PRIMARY KEY) ON COMMIT DROP;
                TRUNCATE pg_temp.sqlos_fga_affected_resources;
                CREATE TEMP TABLE IF NOT EXISTS sqlos_fga_changed_roots (
                    scope_key bigint NOT NULL, resource_id varchar(450) NOT NULL,
                    PRIMARY KEY (scope_key, resource_id)) ON COMMIT DROP;
                TRUNCATE pg_temp.sqlos_fga_changed_roots;

                IF TG_OP = 'INSERT' THEN
                    INSERT INTO pg_temp.sqlos_fga_changed_roots
                    SELECT "ScopeKey", "Id" FROM sqlos_new_resources;
                ELSIF TG_OP = 'DELETE' THEN
                    INSERT INTO pg_temp.sqlos_fga_changed_roots
                    SELECT "ScopeKey", "Id" FROM sqlos_old_resources;
                ELSE
                    INSERT INTO pg_temp.sqlos_fga_changed_roots
                    SELECT n."ScopeKey", n."Id" FROM sqlos_new_resources n
                    JOIN sqlos_old_resources o ON o."ScopeKey" = n."ScopeKey"
                    WHERE n."Id" IS DISTINCT FROM o."Id"
                       OR n."ParentId" IS DISTINCT FROM o."ParentId"
                       OR n."IsActive" IS DISTINCT FROM o."IsActive"
                    UNION
                    SELECT o."ScopeKey", o."Id" FROM sqlos_old_resources o
                    JOIN sqlos_new_resources n ON o."ScopeKey" = n."ScopeKey"
                    WHERE n."Id" IS DISTINCT FROM o."Id"
                       OR n."ParentId" IS DISTINCT FROM o."ParentId"
                       OR n."IsActive" IS DISTINCT FROM o."IsActive";
                END IF;

                IF TG_OP = 'INSERT' THEN
                    -- The managed nondeferrable ParentId FK means an existing resource
                    -- cannot already be a child of an ID first created by this statement.
                    -- Children inserted in the same statement are already in this set.
                    INSERT INTO pg_temp.sqlos_fga_affected_resources
                    SELECT "ScopeKey" FROM sqlos_new_resources;
                ELSIF EXISTS (SELECT 1 FROM pg_temp.sqlos_fga_changed_roots) THEN
                    WITH RECURSIVE affected AS (
                        SELECT scope_key, resource_id FROM pg_temp.sqlos_fga_changed_roots
                        UNION
                        SELECT child."ScopeKey", child."Id"
                        FROM {resources} child JOIN affected parent ON child."ParentId" = parent.resource_id
                    )
                    INSERT INTO pg_temp.sqlos_fga_affected_resources
                    SELECT DISTINCT scope_key FROM affected;
                END IF;

                IF TG_OP = 'UPDATE' THEN
                    INSERT INTO pg_temp.sqlos_fga_affected_resources
                    SELECT n."ScopeKey" FROM sqlos_new_resources n
                    JOIN sqlos_old_resources o ON o."ScopeKey" = n."ScopeKey"
                    WHERE n."ResourceTypeId" IS DISTINCT FROM o."ResourceTypeId"
                    ON CONFLICT DO NOTHING;
                END IF;

                PERFORM {refresh}();
                RETURN NULL;
            END;
            $sqlos$;

            DROP TRIGGER IF EXISTS sqlos_fga_resources_insert_gate ON {resources};
            CREATE TRIGGER sqlos_fga_resources_insert_gate BEFORE INSERT ON {resources}
                FOR EACH STATEMENT EXECUTE FUNCTION {lockFunction}();
            DROP TRIGGER IF EXISTS sqlos_fga_resources_update_gate ON {resources};
            CREATE TRIGGER sqlos_fga_resources_update_gate
                BEFORE UPDATE OF "Id", "ParentId", "IsActive", "ResourceTypeId" ON {resources}
                FOR EACH STATEMENT EXECUTE FUNCTION {lockFunction}();
            DROP TRIGGER IF EXISTS sqlos_fga_resources_delete_gate ON {resources};
            CREATE TRIGGER sqlos_fga_resources_delete_gate BEFORE DELETE ON {resources}
                FOR EACH STATEMENT EXECUTE FUNCTION {lockFunction}();
            DROP TRIGGER IF EXISTS sqlos_fga_resources_inserted ON {resources};
            CREATE TRIGGER sqlos_fga_resources_inserted AFTER INSERT ON {resources}
                REFERENCING NEW TABLE AS sqlos_new_resources
                FOR EACH STATEMENT EXECUTE FUNCTION {changedFunction}();
            DROP TRIGGER IF EXISTS sqlos_fga_resources_updated ON {resources};
            CREATE TRIGGER sqlos_fga_resources_updated AFTER UPDATE ON {resources}
                REFERENCING OLD TABLE AS sqlos_old_resources NEW TABLE AS sqlos_new_resources
                FOR EACH STATEMENT EXECUTE FUNCTION {changedFunction}();
            DROP TRIGGER IF EXISTS sqlos_fga_resources_deleted ON {resources};
            CREATE TRIGGER sqlos_fga_resources_deleted AFTER DELETE ON {resources}
                REFERENCING OLD TABLE AS sqlos_old_resources
                FOR EACH STATEMENT EXECUTE FUNCTION {changedFunction}();
            """
        ];
    }

    private static IReadOnlyList<string> BuildSqlServer(SqlOSFgaOptions options)
    {
        var provider = Provider(false);
        string Q(string name) => provider.Qualify(options.Schema, name);
        var resources = Q(options.TableNames.Resources);
        var types = Q(options.TableNames.ResourceTypes);
        var closure = Q(ClosureTable);
        var gate = Q(GateTable);
        var catalog = Q(CatalogTable);
        var owners = Q(OwnersTable);
        var depth = Math.Max(1, options.MaxResourceHierarchyDepth).ToString(CultureInfo.InvariantCulture);
        var refresh = Q("fn_SqlOSFgaRefreshClosure");
        return [
            $"""
            IF OBJECT_ID(N'{Literal(gate)}', N'U') IS NULL
            BEGIN
                CREATE TABLE {gate} ([Id] int PRIMARY KEY CHECK ([Id] = 1), [Version] bigint NOT NULL);
                INSERT INTO {gate} ([Id], [Version]) VALUES (1, 0);
            END;
            UPDATE {gate} WITH (READCOMMITTEDLOCK) SET [Version] = [Version] + 1 WHERE [Id] = 1;
            IF COL_LENGTH(N'{Literal(resources)}', N'ScopeKey') IS NULL
                ALTER TABLE {resources} ADD [ScopeKey] bigint IDENTITY(1,1) NOT NULL;
            IF COL_LENGTH(N'{Literal(resources)}', N'ProjectionVersion') IS NULL
                ALTER TABLE {resources} ADD [ProjectionVersion] bigint NOT NULL DEFAULT 0;
            IF COL_LENGTH(N'{Literal(types)}', N'TypeKey') IS NULL
                ALTER TABLE {types} ADD [TypeKey] bigint IDENTITY(1,1) NOT NULL;
            """,
            $"""
            IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id = OBJECT_ID(N'{Literal(resources)}') AND name = N'UX_SqlOSFgaResource_ScopeKey')
                CREATE UNIQUE INDEX [UX_SqlOSFgaResource_ScopeKey] ON {resources} ([ScopeKey]);
            IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id = OBJECT_ID(N'{Literal(types)}') AND name = N'UX_SqlOSFgaResourceType_TypeKey')
                CREATE UNIQUE INDEX [UX_SqlOSFgaResourceType_TypeKey] ON {types} ([TypeKey]);
            IF OBJECT_ID(N'{Literal(closure)}', N'U') IS NULL
            BEGIN
                CREATE TABLE {closure} (
                    [DescendantKey] bigint NOT NULL, [AncestorKey] bigint NOT NULL,
                    [Depth] int NOT NULL CHECK ([Depth] >= 0),
                    PRIMARY KEY ([DescendantKey], [AncestorKey]));
                CREATE INDEX [IX_SqlOSFgaResourceClosure_Ancestor] ON {closure} ([AncestorKey], [DescendantKey]);
            END;
            IF OBJECT_ID(N'{Literal(catalog)}', N'U') IS NULL
                CREATE TABLE {catalog} (
                    [Id] varchar(64) PRIMARY KEY, [ModelHash] varchar(64) NOT NULL,
                    [RefreshSql] nvarchar(max) NOT NULL, [DropSql] nvarchar(max) NOT NULL DEFAULT N'');
            IF OBJECT_ID(N'{Literal(owners)}', N'U') IS NULL
            BEGIN
                CREATE TABLE {owners} (
                    [OwnerKey] varchar(64) NOT NULL, [ProjectionId] varchar(64) NOT NULL,
                    PRIMARY KEY ([OwnerKey], [ProjectionId]),
                    FOREIGN KEY ([ProjectionId]) REFERENCES {catalog} ([Id]));
                CREATE INDEX [IX_SqlOSFgaIndexOwners_Projection] ON {owners} ([ProjectionId]);
            END;
            """,
            $"""
            CREATE OR ALTER PROCEDURE {refresh}
            AS
            BEGIN
                SET NOCOUNT ON;
                DELETE c FROM {closure} c WITH (READCOMMITTEDLOCK)
                JOIN #SqlOSFgaAffectedResources affected ON affected.[ScopeKey] = c.[DescendantKey];

                ;WITH ancestors AS (
                    SELECT r.[ScopeKey] AS DescendantKey, r.[ScopeKey] AS AncestorKey,
                           r.[Id], r.[ParentId], 0 AS Depth,
                           CAST(N'|' + r.[Id] + N'|' AS nvarchar(max)) AS VisitedPath,
                           CAST(0 AS bit) AS CycleDetected
                    FROM {resources} r WITH (READCOMMITTEDLOCK)
                    JOIN #SqlOSFgaAffectedResources affected ON affected.[ScopeKey] = r.[ScopeKey]
                    WHERE r.[IsActive] = 1
                    UNION ALL
                    SELECT a.DescendantKey, parent.[ScopeKey], parent.[Id], parent.[ParentId], a.Depth + 1,
                           CAST(a.VisitedPath + parent.[Id] + N'|' AS nvarchar(max)),
                           CAST(CASE WHEN CHARINDEX(N'|' + parent.[Id] + N'|', a.VisitedPath) > 0 THEN 1 ELSE 0 END AS bit)
                    FROM ancestors a
                    JOIN {resources} parent WITH (READCOMMITTEDLOCK) ON parent.[Id] = a.[ParentId]
                    WHERE a.Depth < {depth} AND a.CycleDetected = 0 AND parent.[IsActive] = 1
                )
                INSERT INTO {closure} ([DescendantKey], [AncestorKey], [Depth])
                SELECT a.DescendantKey, a.AncestorKey, a.Depth
                FROM ancestors a
                WHERE NOT EXISTS (
                    SELECT 1 FROM ancestors invalid WHERE invalid.DescendantKey = a.DescendantKey
                      AND (invalid.CycleDetected = 1 OR (invalid.Depth = {depth} AND invalid.[ParentId] IS NOT NULL))
                ) OPTION (MAXRECURSION 0);

                DECLARE @refreshSql nvarchar(max);
                DECLARE registered CURSOR LOCAL FAST_FORWARD FOR
                    SELECT [RefreshSql] FROM {catalog} WITH (READCOMMITTEDLOCK)
                    WHERE [RefreshSql] <> N'' ORDER BY [Id];
                OPEN registered;
                FETCH NEXT FROM registered INTO @refreshSql;
                WHILE @@FETCH_STATUS = 0
                BEGIN
                    EXEC sys.sp_executesql @refreshSql;
                    FETCH NEXT FROM registered INTO @refreshSql;
                END;
                CLOSE registered;
                DEALLOCATE registered;
            END;
            """,
            $"""
            CREATE OR ALTER TRIGGER {Q("tr_SqlOSFgaResourcesChanged")}
            ON {resources} AFTER INSERT, UPDATE, DELETE
            AS
            BEGIN
                SET NOCOUNT ON;
                IF NOT EXISTS (SELECT 1 FROM inserted) AND NOT EXISTS (SELECT 1 FROM deleted) RETURN;
                IF EXISTS (SELECT 1 FROM deleted) AND EXISTS (SELECT 1 FROM inserted)
                   AND NOT EXISTS (
                       SELECT [ScopeKey], [Id], [ParentId], [IsActive], [ResourceTypeId] FROM inserted
                       EXCEPT
                       SELECT [ScopeKey], [Id], [ParentId], [IsActive], [ResourceTypeId] FROM deleted
                   ) AND NOT EXISTS (
                       SELECT [ScopeKey], [Id], [ParentId], [IsActive], [ResourceTypeId] FROM deleted
                       EXCEPT
                       SELECT [ScopeKey], [Id], [ParentId], [IsActive], [ResourceTypeId] FROM inserted
                   ) RETURN;

                DECLARE @version bigint;
                IF NOT EXISTS (SELECT 1 FROM deleted)
                BEGIN
                    SELECT @version = [Version] FROM {gate} WITH (HOLDLOCK, READCOMMITTEDLOCK) WHERE [Id] = 1;
                    IF @version IS NULL THROW 51000, 'The SqlOS resource topology gate is missing.', 1;
                END
                ELSE
                BEGIN
                    UPDATE {gate} WITH (READCOMMITTEDLOCK) SET [Version] = [Version] + 1 WHERE [Id] = 1;
                    IF @@ROWCOUNT = 0 THROW 51000, 'The SqlOS resource topology gate is missing.', 1;
                END;

                CREATE TABLE #SqlOSFgaAffectedResources ([ScopeKey] bigint PRIMARY KEY);
                -- SELECT INTO preserves the resource identifier's real collation instead
                -- of inheriting tempdb's potentially different default. The expression
                -- on ScopeKey deliberately does not copy its IDENTITY property.
                SELECT TOP (0) [ScopeKey] + CONVERT(bigint, 0) AS [ScopeKey], [Id] AS [ResourceId]
                INTO #SqlOSFgaChangedRoots FROM {resources} WITH (READCOMMITTEDLOCK);
                INSERT INTO #SqlOSFgaChangedRoots ([ScopeKey], [ResourceId])
                SELECT n.[ScopeKey], n.[Id] FROM inserted n
                LEFT JOIN deleted o ON o.[ScopeKey] = n.[ScopeKey]
                WHERE o.[ScopeKey] IS NULL OR EXISTS (
                    SELECT n.[Id], n.[ParentId], n.[IsActive]
                    EXCEPT SELECT o.[Id], o.[ParentId], o.[IsActive])
                UNION
                SELECT o.[ScopeKey], o.[Id] FROM deleted o
                LEFT JOIN inserted n ON n.[ScopeKey] = o.[ScopeKey]
                WHERE n.[ScopeKey] IS NULL OR EXISTS (
                    SELECT n.[Id], n.[ParentId], n.[IsActive]
                    EXCEPT SELECT o.[Id], o.[ParentId], o.[IsActive]);
                INSERT INTO #SqlOSFgaAffectedResources ([ScopeKey])
                SELECT DISTINCT [ScopeKey] FROM #SqlOSFgaChangedRoots;

                SELECT TOP (0) [ScopeKey], [ResourceId] INTO #SqlOSFgaFrontier FROM #SqlOSFgaChangedRoots;
                SELECT TOP (0) [ScopeKey], [ResourceId] INTO #SqlOSFgaNext FROM #SqlOSFgaChangedRoots;
                CREATE UNIQUE CLUSTERED INDEX [IX_SqlOSFgaNext_ScopeKey] ON #SqlOSFgaNext ([ScopeKey]);
                -- Existing children of newly inserted IDs are excluded by the managed FK;
                -- all children inserted in this statement are already affected roots.
                IF EXISTS (SELECT 1 FROM deleted)
                    INSERT INTO #SqlOSFgaFrontier SELECT [ScopeKey], [ResourceId] FROM #SqlOSFgaChangedRoots;
                WHILE EXISTS (SELECT 1 FROM #SqlOSFgaFrontier)
                BEGIN
                    INSERT INTO #SqlOSFgaNext ([ScopeKey], [ResourceId])
                    SELECT DISTINCT child.[ScopeKey], child.[Id]
                    FROM {resources} child WITH (READCOMMITTEDLOCK)
                    JOIN #SqlOSFgaFrontier parent ON child.[ParentId] = parent.[ResourceId]
                    WHERE NOT EXISTS (
                        SELECT 1 FROM #SqlOSFgaAffectedResources seen WHERE seen.[ScopeKey] = child.[ScopeKey]);
                    INSERT INTO #SqlOSFgaAffectedResources SELECT [ScopeKey] FROM #SqlOSFgaNext;
                    TRUNCATE TABLE #SqlOSFgaFrontier;
                    INSERT INTO #SqlOSFgaFrontier SELECT [ScopeKey], [ResourceId] FROM #SqlOSFgaNext;
                    TRUNCATE TABLE #SqlOSFgaNext;
                END;

                INSERT INTO #SqlOSFgaAffectedResources ([ScopeKey])
                SELECT n.[ScopeKey] FROM inserted n
                JOIN deleted o ON o.[ScopeKey] = n.[ScopeKey]
                WHERE n.[ResourceTypeId] <> o.[ResourceTypeId]
                  AND NOT EXISTS (SELECT 1 FROM #SqlOSFgaAffectedResources seen WHERE seen.[ScopeKey] = n.[ScopeKey]);

                EXEC {refresh};
            END;
            """
        ];
    }

    private static ISqlOSDatabaseProvider Provider(bool postgres)
        => postgres ? PostgreSqlDatabaseProvider.Instance : SqlServerDatabaseProvider.Instance;

    private static string Literal(string value) => value.Replace("'", "''", StringComparison.Ordinal);
}
