    public async Task<JsonObject> UpsertGroupAsync(SqlOSScimConnection connection, JsonObject payload, bool replace, CancellationToken cancellationToken = default)
    {
        var request = ParseGroup(payload);
        var externalId = NormalizeScimExternalId(request.ExternalId, request.DisplayName);
        var now = DateTime.UtcNow;
        var link = await FindExternalLinkAsync(connection.Id, "Group", externalId, cancellationToken);
        SqlOSFgaUserGroup? group = null;

        if (link != null)
        {
            group = await _context.Set<SqlOSFgaUserGroup>()
                .FirstOrDefaultAsync(x => x.Id == link.EntityId, cancellationToken);
        }

        var created = group == null;
        if (group == null)
        {
            await EnsureFgaSubjectTypeAsync("group", "Group", cancellationToken);
            var subject = new SqlOSFgaSubject
            {
                Id = _cryptoService.GenerateId("subj"),
                SubjectTypeId = "group",
                DisplayName = request.DisplayName,
                OrganizationId = connection.OrganizationId,
                ExternalRef = externalId,
                CreatedAt = now,
                UpdatedAt = now
            };
            group = new SqlOSFgaUserGroup
            {
                Id = _cryptoService.GenerateId("grp"),
                SubjectId = subject.Id,
                Name = request.DisplayName,
                Description = "SCIM mirrored group",
                GroupType = "scim",
                CreatedAt = now,
                UpdatedAt = now
            };
            _context.Set<SqlOSFgaSubject>().Add(subject);
            _context.Set<SqlOSFgaUserGroup>().Add(group);
        }
        else
        {
            group.Name = request.DisplayName;
            group.UpdatedAt = now;
            var subject = await _context.Set<SqlOSFgaSubject>().FirstOrDefaultAsync(x => x.Id == group.SubjectId, cancellationToken);
            if (subject != null)
            {
                subject.DisplayName = request.DisplayName;
                subject.UpdatedAt = now;
            }
        }

        await UpsertExternalLinkAsync(connection.Id, "Group", externalId, group.Id, group.SubjectId, request.DisplayName, true, now, cancellationToken);
        await ReplaceGroupMembersAsync(connection, group, externalId, request.Members, cancellationToken);
        await ApplyGroupMappingsAsync(connection, group, externalId, request.DisplayName, cancellationToken);

        connection.LastSyncAt = now;
        await RecordSyncEventAsync(connection, "Group", group.Id, externalId, created ? "scim.group.created" : "scim.group.updated", "success", null, payload, cancellationToken);
        await RecordAuditAsync(created ? "scim.group.created" : "scim.group.updated", connection.OrganizationId, "Group", group.Id, externalId, payload, cancellationToken);
        await _context.SaveChangesAsync(cancellationToken);
        return await ToScimGroupAsync(connection, group.Id, cancellationToken);
    }

    public async Task<JsonObject> PatchGroupAsync(SqlOSScimConnection connection, string id, JsonObject payload, CancellationToken cancellationToken = default)
    {
        var link = await _context.Set<SqlOSScimExternalId>()
            .FirstOrDefaultAsync(x => x.ConnectionId == connection.Id && x.ResourceType == "Group" && x.EntityId == id, cancellationToken)
            ?? throw new SqlOSScimException(StatusCodes.Status404NotFound, "SCIM group not found.");
        var group = await _context.Set<SqlOSFgaUserGroup>().FirstAsync(x => x.Id == id, cancellationToken);
        var members = await GetCurrentScimGroupMembersAsync(connection.Id, group.Id, cancellationToken);

        foreach (var op in ReadOperations(payload))
        {
            if (string.Equals(op.Path, "displayName", StringComparison.OrdinalIgnoreCase))
            {
                group.Name = op.Value?.GetValue<string>() ?? group.Name;
                link.DisplayName = group.Name;
            }
            else if (string.Equals(op.Path, "members", StringComparison.OrdinalIgnoreCase) || string.IsNullOrWhiteSpace(op.Path))
            {
                var values = ReadMemberValues(op.Value);
                if (string.Equals(op.Op, "remove", StringComparison.OrdinalIgnoreCase))
                {
                    members.RemoveAll(x => values.Contains(x, StringComparer.OrdinalIgnoreCase));
                }
                else
                {
                    foreach (var value in values)
                    {
                        if (!members.Contains(value, StringComparer.OrdinalIgnoreCase))
                        {
                            members.Add(value);
                        }
                    }
                }
            }
        }

        var body = new JsonObject
        {
            ["displayName"] = group.Name,
            ["externalId"] = link.ExternalId,
            ["members"] = new JsonArray(members.Select(value => new JsonObject { ["value"] = value }).ToArray<JsonNode?>())
        };
        return await UpsertGroupAsync(connection, body, replace: false, cancellationToken);
    }

    public async Task DeleteGroupAsync(SqlOSScimConnection connection, string id, CancellationToken cancellationToken = default)
    {
        var link = await _context.Set<SqlOSScimExternalId>()
            .FirstOrDefaultAsync(x => x.ConnectionId == connection.Id && x.ResourceType == "Group" && x.EntityId == id, cancellationToken)
            ?? throw new SqlOSScimException(StatusCodes.Status404NotFound, "SCIM group not found.");

        var group = await _context.Set<SqlOSFgaUserGroup>().FirstOrDefaultAsync(x => x.Id == id, cancellationToken);
        if (group != null)
        {
            var memberships = await _context.Set<SqlOSFgaUserGroupMembership>()
                .Where(x => x.UserGroupId == group.Id)
                .ToListAsync(cancellationToken);
            _context.Set<SqlOSFgaUserGroupMembership>().RemoveRange(memberships);
            await RevokeManagedGrantsForGroupAsync(connection, link.ExternalId, cancellationToken);
        }

        link.IsActive = false;
        link.UpdatedAt = DateTime.UtcNow;
        await RecordSyncEventAsync(connection, "Group", id, link.ExternalId, "scim.group.deleted", "success", null, null, cancellationToken);
        await RecordAuditAsync("scim.group.deleted", connection.OrganizationId, "Group", id, link.ExternalId, null, cancellationToken);
        await _context.SaveChangesAsync(cancellationToken);
    }

    private async Task UpsertPrimaryEmailAsync(SqlOSUser user, string email, DateTime now, CancellationToken cancellationToken)
    {
        var normalized = SqlOSAdminService.NormalizeEmail(email);
        var existing = await _context.Set<SqlOSUserEmail>()
            .FirstOrDefaultAsync(x => x.NormalizedEmail == normalized, cancellationToken);
        if (existing != null && existing.UserId != user.Id)
        {
            throw new SqlOSScimException(StatusCodes.Status409Conflict, $"Email '{email}' already belongs to another user.", "uniqueness");
        }

        if (existing == null)
        {
            existing = new SqlOSUserEmail
            {
                Id = _cryptoService.GenerateId("eml"),
                UserId = user.Id,
                CreatedAt = now
            };
            _context.Set<SqlOSUserEmail>().Add(existing);
        }

        existing.Email = email;
        existing.NormalizedEmail = normalized;
        existing.IsPrimary = true;
        existing.IsVerified = true;
        existing.VerifiedAt ??= now;
    }

    private async Task UpsertMembershipAsync(string organizationId, string userId, bool active, DateTime now, CancellationToken cancellationToken)
    {
        var membership = await _context.Set<SqlOSMembership>()
            .FirstOrDefaultAsync(x => x.OrganizationId == organizationId && x.UserId == userId, cancellationToken);
        if (membership == null)
        {
            membership = new SqlOSMembership
            {
                OrganizationId = organizationId,
                UserId = userId,
                Role = "member",
                CreatedAt = now
            };
            _context.Set<SqlOSMembership>().Add(membership);
        }

        membership.IsActive = active;
    }

    private async Task<string> EnsureFgaUserAsync(SqlOSScimConnection connection, SqlOSUser user, DateTime now, CancellationToken cancellationToken)
    {
        var existingSubjectId = await FindFgaSubjectIdForUserAsync(connection.Id, user.Id, cancellationToken);
        if (!string.IsNullOrWhiteSpace(existingSubjectId))
        {
            var subject = await _context.Set<SqlOSFgaSubject>().FirstOrDefaultAsync(x => x.Id == existingSubjectId, cancellationToken);
            if (subject != null)
            {
                subject.DisplayName = user.DisplayName;
                subject.UpdatedAt = now;
            }

            var fgaUser = await _context.Set<SqlOSFgaUser>().FirstOrDefaultAsync(x => x.SubjectId == existingSubjectId, cancellationToken);
            if (fgaUser != null)
            {
                fgaUser.Email = user.DefaultEmail;
                fgaUser.IsActive = user.IsActive;
            }

            return existingSubjectId;
        }

        await EnsureFgaSubjectTypeAsync("user", "User", cancellationToken);
        var newSubject = new SqlOSFgaSubject
        {
            Id = _cryptoService.GenerateId("subj"),
            SubjectTypeId = "user",
            DisplayName = user.DisplayName,
            OrganizationId = connection.OrganizationId,
            ExternalRef = user.Id,
            CreatedAt = now,
            UpdatedAt = now
        };
        var newUser = new SqlOSFgaUser
        {
            Id = _cryptoService.GenerateId("fusr"),
            SubjectId = newSubject.Id,
            Email = user.DefaultEmail,
            IsActive = user.IsActive
        };
        _context.Set<SqlOSFgaSubject>().Add(newSubject);
        _context.Set<SqlOSFgaUser>().Add(newUser);
        return newSubject.Id;
    }

    private async Task EnsureFgaSubjectTypeAsync(string id, string name, CancellationToken cancellationToken)
    {
        if (!await _context.Set<SqlOSFgaSubjectType>().AnyAsync(x => x.Id == id, cancellationToken))
        {
            _context.Set<SqlOSFgaSubjectType>().Add(new SqlOSFgaSubjectType
            {
                Id = id,
                Name = name
            });
        }
    }

    private async Task<string?> FindFgaSubjectIdForUserAsync(string connectionId, string userId, CancellationToken cancellationToken)
        => await _context.Set<SqlOSScimExternalId>()
            .Where(x => x.ConnectionId == connectionId && x.ResourceType == "User" && x.EntityId == userId)
            .Select(x => x.FgaSubjectId)
            .FirstOrDefaultAsync(cancellationToken)
        ?? await _context.Set<SqlOSFgaSubject>()
            .Where(x => x.SubjectTypeId == "user" && x.ExternalRef == userId)
            .Select(x => x.Id)
            .FirstOrDefaultAsync(cancellationToken);

    private async Task DeprovisionUserAccessAsync(SqlOSScimConnection connection, string userId, string? fgaSubjectId, CancellationToken cancellationToken)
    {
        var membership = await _context.Set<SqlOSMembership>()
            .FirstOrDefaultAsync(x => x.OrganizationId == connection.OrganizationId && x.UserId == userId, cancellationToken);
        if (membership != null)
        {
            membership.IsActive = false;
        }

        var sessions = await _context.Set<SqlOSSession>()
            .Where(x => x.OrganizationId == connection.OrganizationId && x.UserId == userId && x.RevokedAt == null)
            .ToListAsync(cancellationToken);
        foreach (var session in sessions)
        {
            session.RevokedAt = DateTime.UtcNow;
            session.RevocationReason = "scim_deprovisioned";
        }

        if (!string.IsNullOrWhiteSpace(fgaSubjectId))
        {
            var scimGroups = await _context.Set<SqlOSScimExternalId>()
                .Where(x => x.ConnectionId == connection.Id && x.ResourceType == "Group")
                .Select(x => x.EntityId)
                .ToListAsync(cancellationToken);
            var memberships = await _context.Set<SqlOSFgaUserGroupMembership>()
                .Where(x => x.SubjectId == fgaSubjectId && scimGroups.Contains(x.UserGroupId))
                .ToListAsync(cancellationToken);
            _context.Set<SqlOSFgaUserGroupMembership>().RemoveRange(memberships);
        }
    }

    private async Task ReplaceGroupMembersAsync(SqlOSScimConnection connection, SqlOSFgaUserGroup group, string groupExternalId, IReadOnlyList<string> memberValues, CancellationToken cancellationToken)
    {
        var desiredSubjectIds = new HashSet<string>(StringComparer.Ordinal);
        foreach (var value in memberValues)
        {
            var subjectId = await ResolveMemberSubjectIdAsync(connection.Id, value, cancellationToken);
            if (!string.IsNullOrWhiteSpace(subjectId))
            {
                desiredSubjectIds.Add(subjectId);
            }
        }

        var existing = await _context.Set<SqlOSFgaUserGroupMembership>()
            .Where(x => x.UserGroupId == group.Id)
            .ToListAsync(cancellationToken);
        var remove = existing.Where(x => !desiredSubjectIds.Contains(x.SubjectId)).ToList();
        _context.Set<SqlOSFgaUserGroupMembership>().RemoveRange(remove);
        foreach (var removed in remove)
        {
            var data = new { subjectId = removed.SubjectId, groupId = group.Id };
            await RecordSyncEventAsync(connection, "Group", group.Id, groupExternalId, "scim.group.member_removed", "success", null, data, cancellationToken);
            await RecordAuditAsync("scim.group.member_removed", connection.OrganizationId, "Group", group.Id, groupExternalId, data, cancellationToken);
        }

        var existingSubjectIds = existing.Select(x => x.SubjectId).ToHashSet(StringComparer.Ordinal);
        foreach (var subjectId in desiredSubjectIds.Where(subjectId => !existingSubjectIds.Contains(subjectId)))
        {
            _context.Set<SqlOSFgaUserGroupMembership>().Add(new SqlOSFgaUserGroupMembership
            {
                SubjectId = subjectId,
                UserGroupId = group.Id,
                CreatedAt = DateTime.UtcNow
            });
            var data = new { subjectId, groupId = group.Id };
            await RecordSyncEventAsync(connection, "Group", group.Id, groupExternalId, "scim.group.member_added", "success", null, data, cancellationToken);
            await RecordAuditAsync("scim.group.member_added", connection.OrganizationId, "Group", group.Id, groupExternalId, data, cancellationToken);
        }
    }

