    private static ScimUserRequest ParseUser(JsonObject payload)
    {
        var userName = ReadString(payload, "userName") ?? ReadPrimaryEmail(payload) ?? ReadString(payload, "externalId");
        if (string.IsNullOrWhiteSpace(userName))
        {
            throw new SqlOSScimException(StatusCodes.Status400BadRequest, "SCIM userName or primary email is required.", "invalidValue");
        }

        var displayName = ReadString(payload, "displayName")
            ?? payload["name"]?["formatted"]?.GetValue<string>()
            ?? userName;

        return new ScimUserRequest(
            userName.Trim(),
            ReadString(payload, "externalId"),
            ReadPrimaryEmail(payload) ?? userName.Trim(),
            displayName.Trim(),
            payload["active"]?.GetValue<bool>() ?? true);
    }

    private static ScimGroupRequest ParseGroup(JsonObject payload)
    {
        var displayName = ReadString(payload, "displayName");
        if (string.IsNullOrWhiteSpace(displayName))
        {
            throw new SqlOSScimException(StatusCodes.Status400BadRequest, "SCIM group displayName is required.", "invalidValue");
        }

        return new ScimGroupRequest(
            displayName.Trim(),
            ReadString(payload, "externalId"),
            ReadMemberValues(payload["members"]));
    }

    private static List<ScimPatchOperation> ReadOperations(JsonObject payload)
    {
        if (payload["Operations"] is not JsonArray operations)
        {
            throw new SqlOSScimException(StatusCodes.Status400BadRequest, "SCIM PATCH requires Operations.", "invalidSyntax");
        }

        return operations.OfType<JsonObject>()
            .Select(op => new ScimPatchOperation(
                ReadString(op, "op") ?? "replace",
                ReadString(op, "path"),
                op["value"]))
            .ToList();
    }

    private static List<string> ReadMemberValues(JsonNode? node)
    {
        if (node is not JsonArray array)
        {
            return [];
        }

        return array
            .OfType<JsonObject>()
            .Select(item => ReadString(item, "value"))
            .Where(value => !string.IsNullOrWhiteSpace(value))
            .Select(value => value!.Trim())
            .Distinct(StringComparer.OrdinalIgnoreCase)
            .ToList();
    }

    private static string? ReadPrimaryEmail(JsonObject payload)
    {
        if (payload["emails"] is not JsonArray emails)
        {
            return null;
        }

        var objects = emails.OfType<JsonObject>().ToList();
        return objects.FirstOrDefault(x => x["primary"]?.GetValue<bool>() == true)?["value"]?.GetValue<string>()
            ?? objects.FirstOrDefault()?["value"]?.GetValue<string>();
    }

    private static string? ReadString(JsonObject payload, string propertyName)
        => payload.TryGetPropertyValue(propertyName, out var value) && value != null
            ? value.GetValue<string>()
            : null;

    private static string NormalizeScimExternalId(string? externalId, string fallback)
        => string.IsNullOrWhiteSpace(externalId) ? fallback.Trim() : externalId.Trim();

    private static string? TryReadEqFilter(string filter, string attribute)
    {
        var match = Regex.Match(filter, $"^{Regex.Escape(attribute)}\\s+eq\\s+\"(?<value>.+)\"$", RegexOptions.IgnoreCase);
        return match.Success ? match.Groups["value"].Value : null;
    }

    private static (int Skip, int Take, int StartIndex, int Count) ResolveScimPaging(int? startIndex, int? count)
    {
        var resolvedStart = Math.Max(1, startIndex ?? 1);
        var resolvedCount = Math.Clamp(count ?? 100, 1, 200);
        return (resolvedStart - 1, resolvedCount, resolvedStart, resolvedCount);
    }

