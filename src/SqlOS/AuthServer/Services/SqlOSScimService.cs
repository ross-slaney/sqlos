    public async Task<JsonObject> ListUsersAsync(SqlOSScimConnection connection, int? startIndex, int? count, string? filter, CancellationToken cancellationToken = default)
    {
        var users = await _context.Set<SqlOSMembership>()
            .AsNoTracking()
            .Include(x => x.User)
            .Where(x => x.OrganizationId == connection.OrganizationId)
            .Select(x => x.User!)
            .OrderBy(x => x.DefaultEmail ?? x.DisplayName)
            .ToListAsync(cancellationToken);

        if (!string.IsNullOrWhiteSpace(filter))
        {
            var expected = TryReadEqFilter(filter, "userName") ?? TryReadEqFilter(filter, "externalId");
            if (!string.IsNullOrWhiteSpace(expected))
            {
                users = users
                    .Where(x => string.Equals(x.DefaultEmail, expected, StringComparison.OrdinalIgnoreCase)
                        || string.Equals(x.Id, expected, StringComparison.OrdinalIgnoreCase))
                    .ToList();
            }
        }

        var total = users.Count;
        var (skip, take, resolvedStart, resolvedCount) = ResolveScimPaging(startIndex, count);
        var resources = new JsonArray();
        foreach (var user in users.Skip(skip).Take(take))
        {
            resources.Add(await ToScimUserAsync(connection, user, cancellationToken));
        }

        return ListResponse(resources, total, resolvedStart, resolvedCount);
    }

    public async Task<JsonObject> GetUserAsync(SqlOSScimConnection connection, string id, CancellationToken cancellationToken = default)
    {
        var user = await _context.Set<SqlOSUser>()
            .FirstOrDefaultAsync(x => x.Id == id, cancellationToken)
            ?? throw new SqlOSScimException(StatusCodes.Status404NotFound, "SCIM user not found.");

        var membership = await _context.Set<SqlOSMembership>()
            .AnyAsync(x => x.OrganizationId == connection.OrganizationId && x.UserId == user.Id, cancellationToken);
        if (!membership)
        {
            throw new SqlOSScimException(StatusCodes.Status404NotFound, "SCIM user not found.");
        }

        return await ToScimUserAsync(connection, user, cancellationToken);
    }

    public async Task<JsonObject> UpsertUserAsync(SqlOSScimConnection connection, JsonObject payload, bool replace, CancellationToken cancellationToken = default)
    {
        var request = ParseUser(payload);
        var externalId = NormalizeScimExternalId(request.ExternalId, request.UserName);
        var now = DateTime.UtcNow;
        var link = await FindExternalLinkAsync(connection.Id, "User", externalId, cancellationToken);
        SqlOSUser? user = null;

        if (link != null)
        {
            user = await _context.Set<SqlOSUser>().FirstOrDefaultAsync(x => x.Id == link.EntityId, cancellationToken);
        }

        if (user == null && !string.IsNullOrWhiteSpace(request.Email))
        {
            var normalizedEmail = SqlOSAdminService.NormalizeEmail(request.Email);
            var email = await _context.Set<SqlOSUserEmail>()
                .Include(x => x.User)
                .FirstOrDefaultAsync(x => x.NormalizedEmail == normalizedEmail, cancellationToken);
            user = email?.User;
        }

        var created = user == null;
        if (user == null)
        {
            user = new SqlOSUser
            {
                Id = _cryptoService.GenerateId("usr"),
                DisplayName = request.DisplayName,
                DefaultEmail = request.Email,
                IsActive = request.Active,
                CreatedAt = now,
                UpdatedAt = now
            };
            _context.Set<SqlOSUser>().Add(user);
        }
        else
        {
            user.DisplayName = request.DisplayName;
            user.DefaultEmail = request.Email ?? user.DefaultEmail;
            user.IsActive = request.Active;
            user.UpdatedAt = now;
        }

        if (!string.IsNullOrWhiteSpace(request.Email))
        {
            await UpsertPrimaryEmailAsync(user, request.Email, now, cancellationToken);
        }

        await UpsertMembershipAsync(connection.OrganizationId, user.Id, request.Active, now, cancellationToken);
        var fgaSubjectId = await EnsureFgaUserAsync(connection, user, now, cancellationToken);
        await UpsertExternalLinkAsync(connection.Id, "User", externalId, user.Id, fgaSubjectId, user.DisplayName, request.Active, now, cancellationToken);

        if (!request.Active)
        {
            await DeprovisionUserAccessAsync(connection, user.Id, fgaSubjectId, cancellationToken);
        }

        connection.LastSyncAt = now;
        await RecordSyncEventAsync(connection, "User", user.Id, externalId, created ? "scim.user.created" : request.Active ? "scim.user.updated" : "scim.user.deactivated", "success", null, payload, cancellationToken);
        await RecordAuditAsync(created ? "scim.user.created" : request.Active ? "scim.user.updated" : "scim.user.deactivated", connection.OrganizationId, "User", user.Id, externalId, payload, cancellationToken);
        await _context.SaveChangesAsync(cancellationToken);

        return await ToScimUserAsync(connection, user, cancellationToken);
    }

    public async Task<JsonObject> PatchUserAsync(SqlOSScimConnection connection, string id, JsonObject payload, CancellationToken cancellationToken = default)
    {
        var user = await _context.Set<SqlOSUser>()
            .FirstOrDefaultAsync(x => x.Id == id, cancellationToken)
            ?? throw new SqlOSScimException(StatusCodes.Status404NotFound, "SCIM user not found.");
        var membershipExists = await _context.Set<SqlOSMembership>()
            .AnyAsync(x => x.OrganizationId == connection.OrganizationId && x.UserId == user.Id, cancellationToken);
        if (!membershipExists)
        {
            throw new SqlOSScimException(StatusCodes.Status404NotFound, "SCIM user not found.");
        }
        var link = await _context.Set<SqlOSScimExternalId>()
            .AsNoTracking()
            .FirstOrDefaultAsync(x => x.ConnectionId == connection.Id && x.ResourceType == "User" && x.EntityId == user.Id, cancellationToken);

        var active = user.IsActive;
        var displayName = user.DisplayName;
        var email = user.DefaultEmail;
        foreach (var op in ReadOperations(payload))
        {
            var path = op.Path?.Trim();
            if (string.Equals(path, "active", StringComparison.OrdinalIgnoreCase))
            {
                active = op.Value?.GetValue<bool>() ?? active;
            }
            else if (string.Equals(path, "displayName", StringComparison.OrdinalIgnoreCase)
                || string.Equals(path, "name.formatted", StringComparison.OrdinalIgnoreCase))
            {
                displayName = op.Value?.GetValue<string>() ?? displayName;
            }
            else if (string.Equals(path, "userName", StringComparison.OrdinalIgnoreCase))
            {
                email = op.Value?.GetValue<string>() ?? email;
            }
        }

        var body = new JsonObject
        {
            ["externalId"] = link?.ExternalId ?? id,
            ["userName"] = email,
            ["displayName"] = displayName,
            ["active"] = active
        };
        return await UpsertUserAsync(connection, body, replace: false, cancellationToken);
    }

    public async Task DeleteUserAsync(SqlOSScimConnection connection, string id, CancellationToken cancellationToken = default)
    {
        var user = await _context.Set<SqlOSUser>()
            .FirstOrDefaultAsync(x => x.Id == id, cancellationToken)
            ?? throw new SqlOSScimException(StatusCodes.Status404NotFound, "SCIM user not found.");
        var now = DateTime.UtcNow;
        var link = await _context.Set<SqlOSScimExternalId>()
            .FirstOrDefaultAsync(x => x.ConnectionId == connection.Id && x.ResourceType == "User" && x.EntityId == user.Id, cancellationToken);
        var fgaSubjectId = await FindFgaSubjectIdForUserAsync(connection.Id, user.Id, cancellationToken);
        user.IsActive = false;
        user.UpdatedAt = now;
        if (link != null)
        {
            link.IsActive = false;
            link.UpdatedAt = now;
            link.LastSyncedAt = now;
        }
        await DeprovisionUserAccessAsync(connection, user.Id, fgaSubjectId, cancellationToken);
        await RecordSyncEventAsync(connection, "User", user.Id, link?.ExternalId, "scim.user.deactivated", "success", null, null, cancellationToken);
        await RecordAuditAsync("scim.user.deactivated", connection.OrganizationId, "User", user.Id, link?.ExternalId, null, cancellationToken);
        await _context.SaveChangesAsync(cancellationToken);
    }

